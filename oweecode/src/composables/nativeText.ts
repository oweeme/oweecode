export function nativeText(text: string, locale: string): string {
  if (locale === 'es') return text
  return T[locale]?.[text] ?? T.en[text] ?? text
}

/** "Juego 2D — pygame": the part before the dash is translated */
export function gameLabel(label: string, locale: string): string {
  const i = label.indexOf(' — ')
  return i < 0 ? nativeText(label, locale) : nativeText(label.slice(0, i), locale) + label.slice(i)
}
