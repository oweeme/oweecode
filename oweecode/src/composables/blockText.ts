export function blockText(text: string, locale: string): string {
  if (locale === 'es') return text
  return T[locale]?.[text] ?? T.en[text] ?? text
}

/** "DaisyUI · Acciones" -> "DaisyUI · Actions": the part after the dot is translated */
export function blockCategory(category: string, locale: string): string {
  const i = category.indexOf(' · ')
  return i < 0 ? blockText(category, locale) : category.slice(0, i + 3) + blockText(category.slice(i + 3), locale)
}
